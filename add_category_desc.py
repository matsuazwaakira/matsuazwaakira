r = s.get(api("/wp/v2/categories"), params={"per_page":100,"_fields":"id,name,description"})
cats = r.json()

updated = skipped = 0
for c in cats:
    name = c.get("name","")
    if c.get("description","").strip():
        skipped += 1
        continue
    desc = DESCRIPTIONS.get(name)
    if not desc:
        print(f"  定義なし: {name}")
        skipped += 1
        continue
    r2 = s.post(api(f"/wp/v2/categories/{c['id']}"), json={"description": desc})
    if r2.status_code in (200, 201):
        updated += 1
        print(f"  ✅ {name}")
    else:
        print(f"  ✗ {name}: {r2.status_code}")

print(f"\n完了: 設定 {updated}件 / スキップ {skipped}件")
